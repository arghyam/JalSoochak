class TestExecuteAnalytics:
    def _seed_dim(self, conn, user_id: int, scheme_ids=()) -> None:
        import uuid as uuid_mod
        with conn.cursor() as cur:
            cur.execute(
                "INSERT INTO analytics_schema.dim_user_table "
                "(user_id, tenant_id, email, user_type, title, status) "
                "VALUES (%s,%s,%s,1,%s,1)",
                (user_id, TENANT_ID, f"u{user_id}@x.local", f"User {user_id}"),
            )
            for scheme_id in scheme_ids:
                cur.execute(
                    "INSERT INTO analytics_schema.dim_user_scheme_mapping_table "
                    "(uuid, user_id, scheme_id, status, tenant_id) "
                    "VALUES (%s,%s,%s,1,%s)",
                    (str(uuid_mod.uuid4()), user_id, scheme_id, TENANT_ID),
                )

    def test_the_warehouse_ends_up_matching_the_tenant(
            self, db, analytics, roles, tmp_path):
        kept = seed_user(db, "Kept", "919000000001", roles["SECTION_OFFICER"])
        dropped = seed_user(db, "Dropped", "919000000002", roles["SECTION_OFFICER"])
        self._seed_dim(db.conn, kept, [501])
        self._seed_dim(db.conn, dropped, [502, 503])
        roster = master_roster(tmp_path, "USR-1,Kept,9000000001,section-officer")
        plan = build_plan(db, roster, ["SECTION_OFFICER"], [], ACTOR_ID)

        stats = execute_analytics(plan, analytics)

        assert stats == {
            "dim_user_rows_deactivated": 1,
            "dim_user_scheme_mapping_rows_removed": 2,
        }
        with db.conn.cursor() as cur:
            cur.execute(
                "SELECT user_id, status FROM analytics_schema.dim_user_table "
                "ORDER BY user_id"
            )
            assert cur.fetchall() == [(kept, 1), (dropped, USER_STATUS_INACTIVE)]
            cur.execute(
                "SELECT user_id FROM analytics_schema.dim_user_scheme_mapping_table"
            )
            assert [row[0] for row in cur] == [kept]

    def test_another_tenants_rows_are_never_touched(self, db, analytics, roles, tmp_path):
        """dim_user_table.user_id is not unique across tenants — V32 dropped the
        PK — so every warehouse statement has to be tenant-scoped."""
        dropped = seed_user(db, "Dropped", "919000000002", roles["SECTION_OFFICER"])
        with db.conn.cursor() as cur:
            cur.execute(
                "INSERT INTO analytics_schema.dim_tenant_table "
                "(tenant_id, state_code, title, status) VALUES (99, 'MP', 'MP', 1)"
            )
            cur.execute(
                "INSERT INTO analytics_schema.dim_user_table "
                "(user_id, tenant_id, status) VALUES (%s, 99, 1)", (dropped,),
            )
        self._seed_dim(db.conn, dropped)
        roster = master_roster(tmp_path, "USR-1,Somebody Else,9000000001,section-officer")
        plan = build_plan(db, roster, ["SECTION_OFFICER"], [], ACTOR_ID)

        assert [d.user["id"] for d in plan.deletions] == [dropped]
        execute_analytics(plan, analytics)

        with db.conn.cursor() as cur:
            cur.execute(
                "SELECT status FROM analytics_schema.dim_user_table "
                "WHERE tenant_id = 99 AND user_id = %s", (dropped,)
            )
            assert cur.fetchone() == (1,)
