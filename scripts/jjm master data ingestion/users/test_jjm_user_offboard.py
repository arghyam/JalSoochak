class TestLoadLiveUsersByRoles:
    def test_reads_only_the_selected_roles(self, db, roles):
        so = seed_user(db, "Section Officer", "919000000001", roles["SECTION_OFFICER"])
        seed_user(db, "Pump Operator", "919000000002", roles["PUMP_OPERATOR"])
        seed_user(db, "State Admin", "919000000003", roles["STATE_ADMIN"])

        found = db.load_live_users_by_roles(["SECTION_OFFICER"])

        assert [u["id"] for u in found] == [so]
        assert found[0]["role"] == "SECTION_OFFICER"

    def test_skips_users_already_soft_deleted(self, db, roles):
        live = seed_user(db, "Live", "919000000001", roles["SECTION_OFFICER"])
        seed_user(db, "Gone", "919000000002", roles["SECTION_OFFICER"], deleted=True)

        found = db.load_live_users_by_roles(["SECTION_OFFICER"])

        assert [u["id"] for u in found] == [live]

    def test_decrypts_the_name_and_phone_and_judges_the_password(self, db, roles):
        uid = seed_user(db, "Ashif Ahmed", "919000000001", roles["SECTION_OFFICER"],
                        password="an-encrypted-managed-secret", state_user_id="USR-1")

        found = db.load_live_users_by_roles(["SECTION_OFFICER"])

        assert found[0]["id"] == uid
        assert found[0]["name"] == "Ashif Ahmed"
        assert found[0]["phone"] == "919000000001"
        assert found[0]["has_managed_password"] is True
        assert found[0]["state_user_id"] == "USR-1"
        # The secret itself must not travel with the record.
        assert "password" not in found[0]

    def test_an_empty_role_list_reads_nothing(self, db, roles):
        seed_user(db, "Section Officer", "919000000001", roles["SECTION_OFFICER"])

        assert db.load_live_users_by_roles([]) == []

    def test_counts_only_live_scheme_mappings(self, db, roles):
        uid = seed_user(db, "Section Officer", "919000000001", roles["SECTION_OFFICER"])
        seed_mapping(db, uid, 501)
        seed_mapping(db, uid, 502)
        seed_mapping(db, uid, 503, deleted=True)

        assert db.count_live_scheme_mappings([uid]) == {uid: 2}


