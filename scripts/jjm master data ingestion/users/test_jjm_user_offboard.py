def _cli(tmp_path, *extra: str) -> list[str]:
    csv_path = write_csv(
        tmp_path, "users-master.csv", CSV_HEADER, "USR-1,Somebody,9000000001,sdo"
    )
    return [
        "--csv", csv_path, "--actor-id", str(ACTOR_ID),
        "--tenant-dsn", UNREACHABLE_DSN, "--skip-analytics",
        "--out", str(tmp_path / "out.xlsx"), *extra,
    ]


class TestCliGuards:
    @pytest.fixture(autouse=True)
    def pii_keys(self, monkeypatch):
        """Every guard here must fire before a connection is attempted, so the
        keys only have to be well-formed, not real."""
        monkeypatch.setenv("PII_ENCRYPTION_KEY", base64.b64encode(b"\x01" * 32).decode())
        monkeypatch.setenv("PII_HMAC_KEY", base64.b64encode(b"\x02" * 32).decode())

    def test_execute_without_a_ceiling_is_refused(self, tmp_path, caplog):
        code = main(_cli(tmp_path, "--roles", "so", "--execute"))

        assert code == 2
        assert "--max-deletions is required" in caplog.text

    def test_a_scope_of_nothing_offboardable_is_refused(self, tmp_path, caplog):
        code = main(_cli(tmp_path, "--roles", "jal-mitra,khalasi"))

        assert code == 2
        assert "No offboardable role was given" in caplog.text
        assert "PUMP_OPERATOR is a real role" in caplog.text

    def test_a_master_sheet_that_names_nobody_is_refused(self, tmp_path, caplog):
        """A mis-parsed sheet would otherwise read as 'nobody is employed'."""
        path = write_csv(tmp_path, "empty.csv", CSV_HEADER, "USR-1,Bad,123,sdo")
        code = main([
            "--csv", path, "--roles", "so", "--actor-id", str(ACTOR_ID),
            "--tenant-dsn", UNREACHABLE_DSN, "--skip-analytics",
            "--out", str(tmp_path / "out.xlsx"),
        ])

        assert code == 2
        assert "no usable phone number" in caplog.text

    def test_deactivating_still_needs_a_ceiling(self, tmp_path, caplog):
        """A reversible write is still a write against every officer in scope."""
        code = main(_cli(tmp_path, "--roles", "so", "--deactivate-only", "--execute"))

        assert code == 2
        assert "--max-deletions is required" in caplog.text

    def test_a_negative_ceiling_is_refused(self, tmp_path, caplog):
        code = main(_cli(tmp_path, "--roles", "so", "--execute", "--max-deletions", "-1"))

        assert code == 2
        assert "cannot be negative" in caplog.text


