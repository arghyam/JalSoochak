class TestClassifyUsers:
    def test_a_user_no_sheet_names_is_deleted(self, tmp_path):
        roster = master_roster(tmp_path, "USR-1,Still Here,9000000001,sdo")
        users = [db_user(10, "SECTION_OFFICER", "919000000099")]

        decisions = classify_users(users, roster, _pii(), ACTOR_ID)

        assert decisions[0].category == CAT_ABSENT
        assert decisions[0].will_delete

    def test_the_master_spares_whatever_role_it_gives_them(self, tmp_path):
        """A DB section officer the master lists as a jal-mitra is a role change
        for the ingestion to reconcile, not a person to delete."""
        roster = master_roster(tmp_path, "USR-1,Ashif Ahmed,9000000001,jal-mitra")
        users = [db_user(10, "SECTION_OFFICER", "919000000001")]

        decisions = classify_users(users, roster, _pii(), ACTOR_ID)

        assert decisions[0].category == CAT_IN_MASTER
        assert decisions[0].matched_sources == [MASTER_SOURCE]

    def test_a_mapping_sheet_alone_spares_a_user(self, tmp_path):
        roster = master_roster(tmp_path, "USR-1,Somebody Else,9000000002,sdo")
        path = write_csv(
            tmp_path, "so-map.csv", SO_MAPPING_HEADER,
            "SCH-001,1,USR-9,In Service,9000000001",
        )
        load_protect_csv(path, "so-map", 2, "utf-8", roster)
        users = [db_user(10, "SECTION_OFFICER", "919000000001")]

        decisions = classify_users(users, roster, _pii(), ACTOR_ID)

        assert decisions[0].category == CAT_IN_PROTECT
        assert decisions[0].matched_sources == ["so-map"]

    def test_a_logged_in_account_is_never_deleted_by_a_sheet(self, tmp_path):
        roster = master_roster(tmp_path, "USR-1,Somebody Else,9000000002,sdo")
        users = [db_user(10, "EXECUTIVE_ENGINEER", "919000000001",
                         password="k5cmVhbCBtYW5hZ2VkIHNlY3JldA==")]

        decisions = classify_users(users, roster, _pii(), ACTOR_ID)

        assert decisions[0].category == CAT_HAS_LOGIN
        assert not decisions[0].will_delete

