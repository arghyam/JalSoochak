@pytest.fixture
def conn_ready(conn):
    """A throwaway schema inside a transaction that is never committed.

    Nothing here commits, so the rollback at teardown removes the schemas, the
    users and any role row a test created — PostgreSQL rolls DDL back like any
    other statement. That is deliberate: pointing JJM_TEST_DSN at a database
    that matters must not be able to destroy anything in it.
    """
    conn.rollback()  # clear a transaction a previous failure may have aborted
    with conn.cursor() as cur:
        cur.execute("CREATE SCHEMA IF NOT EXISTS common_schema")
        cur.execute(COMMON_DDL)
        # Additive: a real database already holds these, and their ids are read
        # back rather than assumed.
        cur.execute(
            "INSERT INTO common_schema.user_type_master_table (c_name) "
            "VALUES ('SECTION_OFFICER'), ('SUB_DIVISIONAL_OFFICER'), "
            "('EXECUTIVE_ENGINEER'), ('PUMP_OPERATOR'), ('STATE_ADMIN') "
            "ON CONFLICT (c_name) DO NOTHING"
        )
        cur.execute(f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE")
        cur.execute(f"CREATE SCHEMA {SCHEMA}")
        cur.execute(DDL.format(schema=SCHEMA))
        # The actor takes id 1 deliberately. Without them the schema's serial
        # would hand ACTOR_ID to the first user a test seeds, which is spared as
        # the run's own author — quietly turning a deletion test into a no-op
        # that still passes.
        cur.execute(f"""
            INSERT INTO {SCHEMA}.user_table
                (uuid, tenant_id, title, email, user_type, password, status)
            VALUES (gen_random_uuid()::text, %s, 'actor', 'actor@test.local',
                    (SELECT id FROM common_schema.user_type_master_table
                     WHERE c_name = 'STATE_ADMIN'), 'x', 1)
            RETURNING id
        """, (TENANT_ID,))
        assert cur.fetchone()[0] == ACTOR_ID
        cur.execute("DROP SCHEMA IF EXISTS analytics_schema CASCADE")
        cur.execute("CREATE SCHEMA analytics_schema")
        cur.execute(ANALYTICS_DDL)
        cur.execute(
            "INSERT INTO analytics_schema.dim_tenant_table "
            "(tenant_id, state_code, title, status) VALUES (%s, 'AS', 'Assam', 1)",
            (TENANT_ID,),
        )
    yield conn
    conn.rollback()


