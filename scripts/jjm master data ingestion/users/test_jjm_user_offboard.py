        assert rows["SUB_DIVISIONAL_OFFICER"]["affected"] == 1
        assert rows["SUB_DIVISIONAL_OFFICER"]["share_affected"] == "50.0%"
        assert rows["SUB_DIVISIONAL_OFFICER"]["action"] == "soft delete"
        assert rows["SECTION_OFFICER"]["affected"] == 1
        assert rows["SECTION_OFFICER"]["share_affected"] == "100.0%"


