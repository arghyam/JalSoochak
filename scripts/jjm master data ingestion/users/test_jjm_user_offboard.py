def _pii() -> PiiCrypto:
    return PiiCrypto(
        base64.b64encode(b"\x01" * 32).decode(),
        base64.b64encode(b"\x02" * 32).decode(),
    )


def write_csv(tmp_path, name: str, header: str, *lines: str) -> str:
    path = tmp_path / name
    path.write_text(header + "".join(line + "\n" for line in lines), encoding="utf-8")
    return str(path)


def master_roster(tmp_path, *lines: str) -> Roster:
    roster = Roster()
    path = write_csv(tmp_path, "users-master.csv", CSV_HEADER, *lines)
    rows, _ = load_csv(path, header_row=2, encoding="utf-8")
    collect_master(rows, roster)
    return roster


def db_user(user_id: int, role: str, phone: str = "", *, name: str = "Somebody",
            password: str = "CSV_ONBOARDED", state_user_id=None,
            pii: PiiCrypto = None) -> dict:
    """The shape load_live_users_by_roles produces, without a database."""
    pii = pii or _pii()
    return {
        "id": user_id,
        "uuid": f"uuid-{user_id}",
        "name": name,
        "phone": phone,
        "phone_hash": pii.hmac(phone) if phone else "",
        "email": f"so_{phone}@pump-operator.local",
        "status": 1,
        "has_managed_password": has_managed_password(password),
        "state_user_id": state_user_id,
        "role": role,
    }


