class TestSoftDeleteUsers:
    def test_writes_status_and_the_delete_stamp_together(self, db, writer, roles):
        """deleted_at alone would leave the account able to log in: the staff
        login path filters on status, not on deleted_at."""
        uid = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])

        assert writer.soft_delete_users([uid]) == 1

        status, deleted, deleted_by, updated_by = user_row(db, uid)
        assert status == USER_STATUS_INACTIVE
        assert deleted is True
        assert deleted_by == ACTOR_ID
        assert updated_by == ACTOR_ID

    def test_leaves_everybody_else_alone(self, db, writer, roles):
        dropped = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])
        kept = seed_user(db, "Kept", "919000000002", roles["SECTION_OFFICER"])

        writer.soft_delete_users([dropped])

        assert user_row(db, kept) == (1, False, None, None)

    def test_a_user_already_deleted_is_not_touched_again(self, db, writer, roles):
        uid = seed_user(db, "Gone", "919000000001", roles["SECTION_OFFICER"],
                        deleted=True)

        assert writer.soft_delete_users([uid]) == 0

    def test_an_empty_batch_writes_nothing(self, db, writer):
        assert writer.soft_delete_users([]) == 0

    def test_deduplicates_ids_rather_than_double_counting(self, db, writer, roles):
        uid = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])

        assert writer.soft_delete_users([uid, uid]) == 1


class TestSoftDeleteSchemeMappings:
    def test_removes_every_live_mapping_of_the_deleted_users(self, db, writer, roles):
        uid = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])
        seed_mapping(db, uid, 501)
        seed_mapping(db, uid, 502)

        assert writer.soft_delete_scheme_mappings([uid]) == 2
        assert live_mappings(db, uid) == set()

    def test_does_not_touch_another_users_mappings(self, db, writer, roles):
        dropped = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])
        kept = seed_user(db, "Kept", "919000000002", roles["SECTION_OFFICER"])
        seed_mapping(db, dropped, 501)
        seed_mapping(db, kept, 501)

        writer.soft_delete_scheme_mappings([dropped])

        assert live_mappings(db, kept) == {501}

    def test_an_already_deleted_mapping_is_not_restamped(self, db, writer, roles):
        uid = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])
        seed_mapping(db, uid, 501, deleted=True)

        assert writer.soft_delete_scheme_mappings([uid]) == 0

    def test_records_who_dropped_it(self, db, writer, roles):
        uid = seed_user(db, "Dropped", "919000000001", roles["SECTION_OFFICER"])
        mapping_id = seed_mapping(db, uid, 501)

        writer.soft_delete_scheme_mappings([uid])

        with db.conn.cursor() as cur:
            cur.execute(
                f"SELECT deleted_by, updated_by FROM {SCHEMA}.user_scheme_mapping_table "
                f"WHERE id = %s", (mapping_id,)
            )
            assert cur.fetchone() == (ACTOR_ID, ACTOR_ID)


