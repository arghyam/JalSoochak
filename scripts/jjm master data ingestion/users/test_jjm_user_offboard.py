class TestParseRoles:
    @pytest.mark.parametrize("value,expected", [
        ("so", "SECTION_OFFICER"),
        ("SO", "SECTION_OFFICER"),
        ("section-officer", "SECTION_OFFICER"),
        ("SECTION_OFFICER", "SECTION_OFFICER"),
        ("sdo", "SUB_DIVISIONAL_OFFICER"),
        ("SUB_DIVISIONAL_OFFICER", "SUB_DIVISIONAL_OFFICER"),
        ("ee", "EXECUTIVE_ENGINEER"),
        ("executive-engineer", "EXECUTIVE_ENGINEER"),
    ])
    def test_accepts_every_spelling_of_the_three_roles(self, value, expected):
        roles, rejected = parse_roles([value])

        assert roles == [expected]
        assert rejected == []

    def test_splits_on_commas_and_across_repeats(self):
        roles, rejected = parse_roles(["so,sdo", "ee"])

        assert roles == list(OFFBOARDABLE_ROLES)
        assert rejected == []

    def test_deduplicates_without_reordering(self):
        roles, _ = parse_roles(["sdo", "so", "section-officer", "sdo"])

        assert roles == ["SUB_DIVISIONAL_OFFICER", "SECTION_OFFICER"]

    def test_a_real_but_unoffboardable_role_is_skipped_with_a_reason(self):
        """A pump operator is a real role this tool must not touch — saying so is
        different from saying the value was not understood."""
        roles, rejected = parse_roles(["so", "jal-mitra"])

        assert roles == ["SECTION_OFFICER"]
        assert rejected[0]["value"] == "jal-mitra"
        assert rejected[0]["resolved_role"] == "PUMP_OPERATOR"
        assert "not offboardable" in rejected[0]["reason"]

    def test_an_administrative_role_never_enters_scope(self):
        roles, rejected = parse_roles(["state-admin", "super-user"])

        assert roles == []
        assert [r["value"] for r in rejected] == ["state-admin", "super-user"]

    def test_an_unknown_value_is_skipped_rather_than_invented(self):
        roles, rejected = parse_roles(["khalasi"])

        assert roles == []
        assert rejected[0]["resolved_role"] == ""
        assert "not a role this tool recognises" in rejected[0]["reason"]

    def test_blank_values_are_ignored_not_rejected(self):
        roles, rejected = parse_roles(["so,, ,"])

        assert roles == ["SECTION_OFFICER"]
        assert rejected == []


