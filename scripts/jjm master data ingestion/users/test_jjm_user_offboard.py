class TestLoadProtectCsv:
    def test_finds_the_phone_column_whatever_the_sheet_calls_it(self, tmp_path):
        roster = Roster()
        path = write_csv(
            tmp_path, "so-map.csv", SO_MAPPING_HEADER,
            "SCH-001,8156128,USR-100,Ashif Ahmed,7002921268",
        )

        load_protect_csv(path, "so-map", 2, "utf-8", roster)

        assert roster.phone_sources == {"917002921268": ["so-map"]}
        assert roster.public_id_sources == {"usr-100": ["so-map"]}

    def test_reads_the_subdivision_sheets_misspelt_id_column(self, tmp_path):
        roster = Roster()
        path = write_csv(
            tmp_path, "sdo-map.csv", SDO_MAPPING_HEADER,
            "SDV-028,Bihpuria,USR-016067,Pritam Singh,7002506100",
        )

        load_protect_csv(path, "sdo-map", 2, "utf-8", roster)

        assert roster.public_id_sources == {"usr-016067": ["sdo-map"]}

    def test_ignores_public_ids_that_identify_a_scheme_or_a_location(self, tmp_path):
        """scheme_public_id and subdivision_public_id are not people, and letting
        one into the roster would spare a user who happens to share its text."""
        roster = Roster()
        path = write_csv(
            tmp_path, "so-map.csv", SO_MAPPING_HEADER,
            "SCH-001001,8156128,USR-100,Ashif Ahmed,7002921268",
        )

        load_protect_csv(path, "so-map", 2, "utf-8", roster)

        assert "sch-001001" not in roster.public_id_sources
        assert "8156128" not in roster.public_id_sources

    def test_one_phone_named_by_two_sheets_records_both(self, tmp_path):
        roster = master_roster(tmp_path, "USR-1,Ashif Ahmed,7002921268,section-officer")
        path = write_csv(
            tmp_path, "so-map.csv", SO_MAPPING_HEADER,
            "SCH-001,8156128,USR-1,Ashif Ahmed,7002921268",
        )

        load_protect_csv(path, "so-map", 2, "utf-8", roster)

        assert roster.phone_sources["917002921268"] == [MASTER_SOURCE, "so-map"]
        # The healthy case: this sheet names nobody the master left out.
        assert roster.stats[1]["distinct_phones"] == 1
        assert roster.stats[1]["phones_no_earlier_sheet_had"] == 0

    def test_repeated_rows_collapse_to_one_identity(self, tmp_path):
        """The section-officer sheet is one row per scheme: 31k rows, a few
        hundred officers."""
        roster = Roster()
        path = write_csv(
            tmp_path, "so-map.csv", SO_MAPPING_HEADER,
            "SCH-001,1,USR-100,Ashif Ahmed,7002921268",
            "SCH-002,2,USR-100,Ashif Ahmed,7002921268",
            "SCH-003,3,USR-100,Ashif Ahmed,7002921268",
        )

        load_protect_csv(path, "so-map", 2, "utf-8", roster)

        assert list(roster.phone_sources) == ["917002921268"]
        assert roster.stats[0]["rows"] == 3
        assert roster.stats[0]["rows_with_a_usable_phone"] == 3
        assert roster.stats[0]["distinct_phones"] == 1

    def test_a_sheet_without_a_phone_column_is_refused(self, tmp_path):
        """Reading it as protecting nobody is indistinguishable from the file
        being wrong, and would delete everyone it names."""
        roster = Roster()
        path = write_csv(tmp_path, "no-phone.csv", "title,,\na,b,c\n", "1,2,3")

        with pytest.raises(SystemExit, match="no phone column"):
            load_protect_csv(path, "no-phone", 2, "utf-8", roster)


