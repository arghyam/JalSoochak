def seed_user(db: OffboardDb, name: str, phone: str, user_type: int, *,
              password: str = "CSV_ONBOARDED", state_user_id=None,
              status: int = 1, deleted: bool = False) -> int:
    import uuid as uuid_mod
    with db.conn.cursor() as cur:
        cur.execute(f"""
            INSERT INTO {SCHEMA}.user_table
                (uuid, tenant_id, title, title_hash, email, user_type,
                 phone_number, phone_number_hash, state_user_id, password, status,
                 deleted_at)
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,{'NOW()' if deleted else 'NULL'})
            RETURNING id
        """, (
            str(uuid_mod.uuid4()), TENANT_ID,
            db.pii.encrypt(name), db.pii.title_hash(name),
            f"seed_{phone or uuid_mod.uuid4()}@pump-operator.local", user_type,
            db.pii.encrypt(phone) if phone else None,
            db.pii.hmac(phone) if phone else None,
            state_user_id, password, status,
        ))
        return cur.fetchone()[0]


def seed_mapping(db: OffboardDb, user_id: int, scheme_id: int, deleted: bool = False) -> int:
    with db.conn.cursor() as cur:
        cur.execute(
            f"INSERT INTO {SCHEMA}.user_scheme_mapping_table "
            f"(user_id, scheme_id, status, deleted_at) "
            f"VALUES (%s,%s,1,{'NOW()' if deleted else 'NULL'}) RETURNING id",
            (user_id, scheme_id),
        )
        return cur.fetchone()[0]


def user_row(db: OffboardDb, user_id: int) -> tuple:
    with db.conn.cursor() as cur:
        cur.execute(
            f"SELECT status, deleted_at IS NOT NULL, deleted_by, updated_by "
            f"FROM {SCHEMA}.user_table WHERE id = %s", (user_id,)
        )
        return cur.fetchone()


def live_mappings(db: OffboardDb, user_id: int) -> set[int]:
    with db.conn.cursor() as cur:
        cur.execute(
            f"SELECT scheme_id FROM {SCHEMA}.user_scheme_mapping_table "
            f"WHERE user_id = %s AND deleted_at IS NULL", (user_id,)
        )
        return {row[0] for row in cur}


