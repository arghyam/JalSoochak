class TestMapping:
    def test_an_officer_gets_the_union_of_their_rows(self, db, tmp_path, writers):
        first = seed_scheme(db, "100")
        second = seed_scheme(db, "200")

        plan = plan_for(
            db, tmp_path,
            "SCH-1,100,USR-1,Ashif Ahmed,9000000001",
            "SCH-2,200,USR-1,Ashif Ahmed,9000000001",
        )
        assert len(plan.officers) == 1
        assert officer(plan).to_insert == {first, second}

        stats = execute_tenant(plan, *writers)

        assert stats["scheme_mappings_inserted"] == 2
        assert live_mappings(db, officer(plan).decision.existing_id) == {first, second}

    def test_a_mapping_already_held_is_not_inserted_again(self, db, tmp_path, roles, writers):
        held = seed_scheme(db, "100")
        wanted = seed_scheme(db, "200")
        user = seed_user(db, "A", "919000000001", roles[SO_ROLE])
        seed_mapping(db, user, held)

        plan = plan_for(
            db, tmp_path,
            "SCH-1,100,USR-1,A,9000000001",
            "SCH-2,200,USR-1,A,9000000001",
        )
        assert officer(plan).to_insert == {wanted}

        stats = execute_tenant(plan, *writers)

        assert stats["scheme_mappings_inserted"] == 1
        assert stats["scheme_mappings_already_correct"] == 1
