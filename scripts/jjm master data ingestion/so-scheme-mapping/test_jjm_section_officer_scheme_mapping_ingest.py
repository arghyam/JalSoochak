class TestCollapseOfficers:
    def test_one_officer_over_many_rows_becomes_one_user_row(self, tmp_path):
        rows, _ = rows_of(
            tmp_path,
            "SCH-1,100,USR-1,Same Person,9000000001",
            "SCH-2,200,USR-1,Same Person,9000000001",
            "SCH-3,300,USR-2,Other Person,9000000002",
        )

        user_rows, grouped = collapse_officers(rows)

        assert len(user_rows) == 2
        assert user_rows[0].phone == "919000000001"
        assert [r.row_no for r in grouped["919000000001"]] == [3, 4]

    def test_name_and_public_id_are_taken_across_the_group(self, tmp_path):
        """Not off whichever row came first: an officer with 166 rows may have a
        gap on the one that happens to sort first, and that must not onboard
        them nameless — or block them as an unusable row."""
        rows, _ = rows_of(
            tmp_path,
            "SCH-1,100,,,9000000001",
            "SCH-2,200,USR-7,Pallabi Das,9000000001",
        )

        user_rows, _ = collapse_officers(rows)

        assert len(user_rows) == 1
        assert user_rows[0].name == "Pallabi Das"
        assert user_rows[0].public_id == "USR-7"
        assert user_rows[0].blocking_issues == []

    def test_an_officer_with_no_name_anywhere_is_still_unusable(self, tmp_path):
        rows, _ = rows_of(tmp_path, "SCH-1,100,USR-1,,9000000001")

        user_rows, _ = collapse_officers(rows)

        assert user_rows[0].blocking_issues == ["row:blank section_officer_name"]

    def test_rows_with_no_usable_number_stay_separate(self, tmp_path):
        """Two people we cannot identify are not the same person."""
        rows, _ = rows_of(
            tmp_path,
            "SCH-1,100,USR-1,A,111",
            "SCH-2,200,USR-2,B,222",
        )

        user_rows, _ = collapse_officers(rows)

        assert len(user_rows) == 2


