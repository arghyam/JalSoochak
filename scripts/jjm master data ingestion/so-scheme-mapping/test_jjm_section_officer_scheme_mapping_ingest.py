"""Tests for jjm_section_officer_scheme_mapping_ingest.

Two layers:

  * pure logic — CSV parsing (including the literal 'NULL' this export writes
    into imis_id), the collapse of up to 166 rows onto one officer, and the role
    gate. These run anywhere.
  * write paths — scheme resolution, stale-mapping detection and every
    INSERT/UPDATE/soft-delete against a real PostgreSQL. Resolution reads an
    index built from the tenant's own rows, the stale query joins three tables
    to isolate one role, and the writes build SQL dynamically; a mock cannot
    show that any of that executes, types its columns correctly, or lands the
    right values on the right rows.

What is deliberately *not* re-tested here is the user half — matching on phone,
the field-level diff, the protected roles, the onboarding row. That is
users/test_jjm_user_master_ingest.py's job, and this module imports the same
code. What is tested is everything the scheme/SO contract adds: resolving a
scheme by its centre id rather than through a departmental node, the fan-out
that a centre id shared by several schemes produces, and the removal rule —
which is this tool's only destructive behaviour and the one thing none of its
siblings do by default.

The tenant DDL and the user/mapping seed helpers are imported from the
division/EE suite for the same reason the production module imports its engine —
one schema definition, not two that drift.

  export JJM_TEST_DSN='postgresql://postgres:testpw@localhost:55432/shared_db'
  python3 -m pytest "scripts/jjm master data ingestion/so-scheme-mapping/test_jjm_section_officer_scheme_mapping_ingest.py" -v
"""

