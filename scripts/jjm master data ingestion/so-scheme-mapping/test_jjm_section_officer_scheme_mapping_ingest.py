# A DSN nothing can be listening on, so a run that gets *past* the guard dies on
# connect instead of writing to whatever tenant_as the runner happens to have.
UNREACHABLE_DSN = "postgresql://postgres:x@127.0.0.1:1/none"


def _cli(tmp_path, *extra: str) -> list[str]:
    return [
        "--csv", write_csv(tmp_path, "SCH-1,100,USR-1,A,9000000001"),
        "--actor-id", "1", "--tenant-dsn", UNREACHABLE_DSN, "--skip-analytics",
        "--out", str(tmp_path / "out.xlsx"), *extra,
    ]


def _run_cli(tmp_path, *extra: str) -> None:
    """Call main and swallow whatever it hits once the guard has let it through."""
    with contextlib.suppress(Exception, SystemExit):
        main(_cli(tmp_path, *extra))


class TestCli:
    def test_a_truncated_run_may_not_execute_a_removal(self, tmp_path, caplog):
        """One row per scheme means a cut file is a cut statement of who covers
        what — every mapping past the cut would read as taken away."""
        code = main(_cli(tmp_path, "--limit", "1", "--execute"))

        assert code == 2
        assert "--limit cannot be combined with --execute" in caplog.text

    def test_a_truncated_rehearsal_is_fine(self, tmp_path, caplog):
        _run_cli(tmp_path, "--limit", "1")

        assert "--limit cannot be combined" not in caplog.text

    def test_a_truncated_run_may_execute_when_it_removes_nothing(self, tmp_path, caplog):
        _run_cli(tmp_path, "--limit", "1", "--execute", "--additive")

        assert "--limit cannot be combined" not in caplog.text

    def test_a_zero_limit_is_refused_rather_than_ignored(self, tmp_path, caplog):
        """A falsy limit used to slip past both the guard and the slice, so
        --limit 0 --execute quietly ran the whole file."""
        code = main(_cli(tmp_path, "--limit", "0", "--execute"))

        assert code == 2
        assert "--limit must be a positive number of rows" in caplog.text


