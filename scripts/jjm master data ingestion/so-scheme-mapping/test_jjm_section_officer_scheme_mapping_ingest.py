def seed_scheme(db: SoDb, centre_id: str, state_id: str = "", name: str = "",
                deleted: bool = False, is_active: bool = True) -> int:
    """A scheme identified the way the tenant identifies one: a centre id and a
    state id, unique as a pair rather than singly."""
    with db.conn.cursor() as cur:
        cur.execute(
            f"INSERT INTO {db.schema}.scheme_master_table "
            f"(uuid, state_scheme_id, centre_scheme_id, scheme_name, is_active, deleted_at) "
            f"VALUES (gen_random_uuid()::text, %s, %s, %s, %s, "
            f"{'NOW()' if deleted else 'NULL'}) RETURNING id",
            (state_id or centre_id, centre_id, name or f"Scheme {centre_id}", is_active),
        )
        return cur.fetchone()[0]


def seed_dim_scheme(db: SoDb, scheme_id: int) -> None:
    with db.conn.cursor() as cur:
        cur.execute(
            "INSERT INTO analytics_schema.dim_scheme_table (scheme_id, tenant_id) "
            "VALUES (%s, %s)", (scheme_id, TENANT_ID),
        )


def plan_for(db, tmp_path, *lines: str, **kwargs) -> SoIngestPlan:
    rows, issues = rows_of(tmp_path, *lines)
    return build_plan(rows, issues, db, **kwargs)


def officer(plan: SoIngestPlan, index: int = 0):
    return plan.officers[index]


def live_mappings(db: SoDb, user_id: int) -> set[int]:
    with db.conn.cursor() as cur:
        cur.execute(
            f"SELECT scheme_id FROM {db.schema}.user_scheme_mapping_table "
            f"WHERE user_id = %s AND deleted_at IS NULL", (user_id,)
        )
        return {scheme_id for (scheme_id,) in cur}


